from __future__ import annotations

import re
from dataclasses import dataclass
from typing import List


@dataclass(frozen=True)
class Rule:
    name: str
    pattern: str
    weight: float
    level: str
    why: str
    advice: str

    @property
    def regex(self) -> re.Pattern:
        return re.compile(self.pattern)


